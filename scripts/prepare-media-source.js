#!/usr/bin/env node
// Restores any media file listed in automation/media-manifest.json that is missing from the
// local checkout — the state Git will be in once history no longer carries migrated media —
// by downloading it back from the public R2 delivery domain. Everything downstream (image
// dimension reads, responsive-variant generation, LQIP, video-poster regeneration) still reads
// these files straight off disk under blog/assets/images|videos/, exactly as before; only their
// origin changes from "committed in Git" to "materialized here from R2 on demand". Content that
// lives only as ephemeral build output (_site/assets/images/responsive/**) is skipped — that is
// regenerated by every build regardless and was never meant to be restored as a source.
//
// Safe to run at any time: files already present on disk (the common case today, since nothing
// has been removed from Git yet) are left untouched.

const fs = require("fs");
const path = require("path");

const { loadManifest, downloadMediaFile, optionalCredentialsFromEnv } = require("./lib/r2-media");
const { objectKeyFor } = require("../lib/media-manifest");

const root = process.cwd();
const ephemeralSourcePrefix = "_site/";
const concurrency = Number.parseInt(process.env.MEDIA_SOURCE_DOWNLOAD_CONCURRENCY || "16", 10);

// Mirrors scripts/publish-build-media.js's worker pool: with well over a thousand manifest
// entries, downloading them one at a time would make every cold build (a fresh CI runner, or
// anyone re-cloning the repo) wait on over a thousand sequential HTTPS round-trips.
async function runWithConcurrency(items, limit, worker) {
  let next = 0;

  async function runNext() {
    const index = next;
    next += 1;
    if (index >= items.length) return;
    await worker(items[index]);
    await runNext();
  }

  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, runNext));
}

async function main() {
  const manifest = loadManifest();
  const missing = Object.entries(manifest)
    .filter(([, entry]) => entry.sourcePath && !entry.sourcePath.startsWith(ephemeralSourcePrefix))
    .map(([key, entry]) => ({
      key,
      objectKey: objectKeyFor(entry, key),
      destinationPath: path.join(root, entry.sourcePath),
      sha256: entry.sha256
    }))
    .filter(({ destinationPath }) => !fs.existsSync(destinationPath));

  await runWithConcurrency(missing, concurrency, ({ key, objectKey, destinationPath, sha256 }) =>
    downloadMediaFile({ key, objectKey, destinationPath, expectedSha256: sha256 })
  );

  const total = Object.values(manifest).filter(
    (entry) => entry.sourcePath && !entry.sourcePath.startsWith(ephemeralSourcePrefix)
  ).length;
  // Naming the route is what makes a CI run evidence rather than inference: both routes end in
  // the same success line, but only one of them is immune to an edge cache answering for an
  // object that has since been replaced. If this ever reads "public delivery domain" in a
  // production build, the credentials stopped reaching the gate — see
  // .github/actions/validate-site/action.yml.
  const route = optionalCredentialsFromEnv() ? "R2 bucket (signed S3 API)" : "public delivery domain";
  console.log(
    `Media source prepare: ${missing.length} file(s) restored from ${route}, ${total - missing.length} already present.`
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
