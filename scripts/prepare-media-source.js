#!/usr/bin/env node
// Restores any media file listed in automation/media-manifest.json that is missing from the
// local checkout — the state Git will be in once history no longer carries migrated media —
// by downloading it back from the public R2 delivery domain. Everything downstream (image
// dimension reads, responsive-variant generation, LQIP, video-poster regeneration) still reads
// these files straight off disk under blog/assets/images|videos/, exactly as before; only their
// origin changes from "committed in Git" to "materialized here from R2 on demand". Content that
// lives only as ephemeral build output (_site/assets/images/responsive/**) is skipped — that is
// regenerated by every build regardless and was never meant to be restored as a source.
//
// Safe to run at any time: files already present on disk (the common case today, since nothing
// has been removed from Git yet) are left untouched.

const fs = require("fs");
const path = require("path");

const { loadManifest, downloadMediaFile } = require("./lib/r2-media");

const root = process.cwd();
const ephemeralSourcePrefix = "_site/";

async function main() {
  const manifest = loadManifest();
  const entries = Object.entries(manifest).filter(
    ([, entry]) => entry.sourcePath && !entry.sourcePath.startsWith(ephemeralSourcePrefix)
  );

  let restored = 0;
  for (const [key, entry] of entries) {
    const destinationPath = path.join(root, entry.sourcePath);
    if (fs.existsSync(destinationPath)) continue;

    await downloadMediaFile({ key, destinationPath, expectedSha256: entry.sha256 });
    restored += 1;
  }

  console.log(`Media source prepare: ${restored} file(s) restored from R2, ${entries.length - restored} already present.`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
